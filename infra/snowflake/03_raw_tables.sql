-- =====================================================================
-- 03_raw_tables.sql : Bronze (RAW) tables, one per Inside Airbnb file.
-- Run as TRANSFORMER after 02_integration_and_stage.sql.
--
-- Rules for RAW:
--   * every source column is VARCHAR (text), named exactly as the CSV
--     header, in the same order: no type guessing, nothing can fail to cast;
--     typing and cleaning happen in dbt Silver models (Phase 3);
--   * four metadata columns, all starting with an underscore:
--       _source_file    full S3 path of the file the row came from
--       _source_row     row number inside that file
--       _snapshot_date  Inside Airbnb snapshot the file belongs to
--       _loaded_at      when COPY INTO inserted the row
--   * append-only: rows are only ever inserted by COPY INTO.
-- Generated from the real file headers (identical in 2026-06-19 and
-- 2026-09-17). Safe to rerun (IF NOT EXISTS).
-- =====================================================================

