CREATE TABLE IF NOT EXISTS CALENDAR (
    LISTING_ID VARCHAR,
    DATE VARCHAR,
    AVAILABLE VARCHAR,
    MINIMUM_NIGHTS VARCHAR,
    MAXIMUM_NIGHTS VARCHAR,
    _SOURCE_FILE VARCHAR NOT NULL,
    _SOURCE_ROW NUMBER NOT NULL,
    _SNAPSHOT_DATE DATE NOT NULL,
    _LOADED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'One row per listing per date per snapshot, exactly as in calendar.csv.gz. Note: no price column.';

CREATE TABLE IF NOT EXISTS REVIEWS (
    LISTING_ID VARCHAR,
    ID VARCHAR,
    DATE VARCHAR,
    REVIEWER_ID VARCHAR,
    REVIEWER_NAME VARCHAR,
    COMMENTS VARCHAR,
    _SOURCE_FILE VARCHAR NOT NULL,
