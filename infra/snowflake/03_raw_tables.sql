    _SNAPSHOT_DATE DATE NOT NULL,
    _LOADED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'One row per review per snapshot, exactly as in reviews.csv.gz (each snapshot repeats all past reviews).';
